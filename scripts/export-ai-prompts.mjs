// Writes docs/AI_PROMPTS.md from netlify/functions/ai/prompts.mjs, with sample inputs and expected outputs (handover item).
// Run: npm run ai-prompts
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { HELP_SYSTEM, READ_ENTRY_SYSTEM, READ_STATEMENT_SYSTEM } from "../netlify/functions/ai/prompts.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const block = (s) => "```text\n" + s + "\n```";
const json = (o) => "```json\n" + JSON.stringify(o, null, 2) + "\n```";
const md = `# AI instructions (prompts)

Source of truth: \`netlify/functions/ai/prompts.mjs\` (this file is generated by \`npm run ai-prompts\`).
The browser calls \`/.netlify/functions/ai\` with a task; the function adds the key (\`AI_API_KEY\`) and model (\`AI_MODEL\`, default \`claude-haiku-5-5\`) and calls the Claude Messages API. If the key is missing or the call fails, it answers \`{"fallback": true}\` and the app uses its own rules (\`src/core/reader.js\`, \`src/core/statements.js\`, FAQ search), labelled on screen.

The AI only **suggests** an entry type. The accounting engine decides the journal lines, and the business confirms the plain-language reading before anything posts.

## 1. Entry reading (task \`read_entry\`)

Request from the app: \`{"task": "read_entry", "text": "...", "direction": "in" | "out" | null, "lang": "sw" | "en"}\`

System prompt:

${block(READ_ENTRY_SYSTEM)}

User message sent: \`Direction chosen: in\\nDescription: nimeuza mboga elfu ishirini cash\`

| Input (direction) | Expected output (key fields) |
|---|---|
| "nimeuza mboga elfu ishirini cash" (in) | \`kind: sale_cash, amount: 20000, channel: cash\` |
| "mteja amelipa deni lake 15k mpesa" (in) | \`kind: debtor_receipt, amount: 15000, channel: mobile\` |
| "nimelipa kodi ya pango laki moja" (out) | \`kind: rent, amount: 100000\` |
| "nimechangia mchezo elfu kumi" (out) | \`kind: group_contribution, amount: 10000\` |
| "ada ya shule ya mtoto 50,000" (out) | \`kind: drawings, amount: 50000\` |
| "nimehamisha elfu hamsini kutoka mpesa kwenda benki" (null) | \`kind: transfer, amount: 50000\` |
| "nimeuza" chosen as money out | \`kind: sale_cash, conflict: true\` (held for Data Admin if posted) |
| "xyz" (in) | \`kind: null\` with one simple question in both languages |

Example full reply:

${json({ kind: "sale_cash", alternatives: ["debtor_receipt", "other_income"], amount: 20000, channel: "cash", confidence: 0.93, conflict: false, question_en: null, question_sw: null })}

## 2. Statement reading (task \`read_statement\`)

Request: \`{"task": "read_statement", "text": "<text extracted from the PDF, up to 20,000 characters>", "lang": "sw"}\`

System prompt:

${block(READ_STATEMENT_SYSTEM)}

Sample input: the text of \`public/samples/mpesa-statement-neema.pdf\`. Expected output (first lines):

${json({ account_name: "NEEMA JUMA MUSHI", provider: "M-PESA", lines: [{ date: "2026-09-26", description: "Customer payment from JOHN PETER", reference: "", amountIn: 25000, amountOut: 0, balance: 145000 }, { date: "2026-09-28", description: "Payment to LUKU electricity token", reference: "", amountIn: 0, amountOut: 15000, balance: 130000 }] })}

The app then runs its own reliability checks (name, layout, running balance, dates, already-recorded lines) whatever the AI returns.

## 3. Help chat (task \`help\`)

Request: \`{"task": "help", "question": "...", "lang": "sw", "faq": [{"q": "...", "a": "..."}]}\` (the FAQ for the user's type, in their language)

System prompt:

${block(HELP_SYSTEM)}

| Question | Expected |
|---|---|
| "Nifanye nini nikisahau kufunga siku?" | Answer from the FAQ (catch-up, then one count), \`confident: true\` |
| "Can I change my NIDA number?" | Short answer that Admin will help, \`confident: false\` → the app offers "Send to TijaPass Admin" |

## Native build notes

- Keep the key on the server; never in the app.
- Log the model, prompt version and reply with each suggestion so Data Admin can review AI recommendations on held entries.
- Voice: send the speech-to-text transcript as the description; the same prompt handles it.
`;
fs.writeFileSync(path.join(root, "docs/AI_PROMPTS.md"), md);
console.log("docs/AI_PROMPTS.md written");
